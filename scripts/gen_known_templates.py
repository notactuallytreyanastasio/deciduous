#!/usr/bin/env python3
"""Regenerate src/init/known_templates.rs: the sha256 of every harness template text
this repository ever produced, on any branch, normalised (lines right-stripped, whole
text stripped). `deciduous update` uses it to tell a file deciduous wrote, which it may
replace, from one the user wrote, which it must keep.

    python3 scripts/gen_known_templates.py --write

Not `> src/init/known_templates.rs`: the shell empties the file before this reads it,
and the hashes kept from the list as it was (branches this clone does not have) are lost.
"""
import hashlib, re, subprocess, sys
RAW = re.compile(r'r(#+)"(.*?)"\1', re.S)
PATHS = re.compile(r"init|template|opencode|hooks|windsurf")
def norm(s): return "\n".join(l.rstrip() for l in s.replace("\r\n", "\n").strip().splitlines())
def git(*a): return subprocess.run(["git", *a], capture_output=True, text=True).stdout
known, blobs = set(), set()
for rev in git("log", "--all", "--format=%H", "--", "src").split():
    for line in git("ls-tree", "-r", rev, "src").splitlines():
        meta, path = line.split("\t", 1); blob = meta.split()[2]
        if not path.endswith(".rs") or blob in blobs or not PATHS.search(path): continue
        blobs.add(blob)
        for m in RAW.finditer(git("cat-file", "-p", blob)):
            t = norm(m.group(2))
            if len(t) >= 80:  # templates, not format strings or short literals
                known.add(hashlib.sha256(t.encode()).hexdigest())
# A hash already in the list stays: it came from a branch some clone had, and a
# clone without that branch must not un-know a template deciduous shipped.
here = len(known)
try: known |= set(re.findall(r'"([0-9a-f]{64})"', open("src/init/known_templates.rs").read()))
except FileNotFoundError: pass
out = []
out.append("// @generated by scripts/gen_known_templates.py; do not edit by hand.")
out.append("// sha256 of every harness template deciduous ever shipped, normalised.")
out.append(f"// {len(known)} texts: {here} from {len(blobs)} source blobs in this clone, {len(known) - here} kept from the list as it was.")
out.append("pub const KNOWN_TEMPLATE_SHA256: &[&str] = &[")
for h in sorted(known): out.append(f'    "{h}",')
out.append("];")
text = "\n".join(out) + "\n"
if "--write" in sys.argv: open("src/init/known_templates.rs", "w").write(text)
else: sys.stdout.write(text)
